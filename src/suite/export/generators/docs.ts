import { PdfDoc } from './pdfKit'
import type { ManufacturingProject } from '../types'

export function generateSizeChartPdf(p: ManufacturingProject): Blob {
  const pdf = new PdfDoc('Size Chart')
  pdf.cover(p, `Graded measurement chart · ${p.sizes.join(' / ')}`)
  pdf.section('Measurement Chart (cm)')
  pdf.table(
    ['Code', 'Point of measure', ...p.sizes, 'Tolerance'],
    p.measurements.map((r) => [r.code, r.point, ...p.sizes.map((s) => r.values[s].toFixed(1)), `±${r.toleranceCm.toFixed(1)}`]),
    [0.5, 2.4, ...p.sizes.map(() => 0.6), 0.7],
  )
  pdf.section('Measurement Guide')
  pdf.bullets([
    'All measurements are half-body (HB) unless noted, taken flat with garment relaxed.',
    'Chest is measured 1cm below the armhole seam-to-seam.',
    'Body length is measured from the highest point of shoulder (HPS) to hem.',
    'Grading is consistent across the size run; confirm the sealed sample before bulk.',
    `Applied tolerance per point is listed above; out-of-tolerance measurements are rejected.`,
  ])
  return pdf.finalizeAndBlob()
}

