export function generateColorReferencesPdf(p: ManufacturingProject): Blob {
  const pdf = new PdfDoc('Color References')
  pdf.cover(p, 'HEX · RGB · Pantone')
  pdf.section('Approved Colorway')
  // swatch grid
  const doc = pdf.doc
  let yy = 78 + 60 // after section
  // draw swatches manually via table + colored chips
  p.colors.forEach((c) => {
    const x = pdf.margin
    doc.setFillColor(c.rgb[0], c.rgb[1], c.rgb[2])
    doc.roundedRect(x, yy - 12, 34, 34, 5, 5, 'F')
    doc.setDrawColor(220, 220, 224)
    doc.roundedRect(x, yy - 12, 34, 34, 5, 5, 'S')
    doc.setTextColor(18, 18, 24)
    doc.setFont('helvetica', 'bold')
    doc.setFontSize(11)
    doc.text(c.name, x + 48, yy)
    doc.setFont('helvetica', 'normal')
    doc.setFontSize(9)
    doc.setTextColor(120, 120, 132)
    doc.text(`HEX ${c.hex}    RGB ${c.rgb.join(', ')}    ${c.pantone}`, x + 48, yy + 15)
    yy += 48
  })
  return pdf.finalizeAndBlob()
}

